#!/usr/bin/env node
// 结构索引生成：把 src/ 与 src-tauri/ 的逐文件事实整体写成 docs/CODE-INDEX.md
// 只做机械提取（路径 → 领域 / 角色 / 关键导出 / 行数），不含语义判断。
// docs/CODE-INDEX.md 全文由本脚本产出，不含手写内容；
// 手写语义（分层、边界、改动路由）留在 docs/CODE-STRUCTURE.md。
//
// 用法：
//   node scripts/structure-index.mjs                   生成 docs/CODE-INDEX.md（全量）
//   node scripts/structure-index.mjs frontend          仅前端 src/
//   node scripts/structure-index.mjs rust              仅后端 src-tauri/
//   node scripts/structure-index.mjs app               仅 src-tauri/src + 根文件
//   node scripts/structure-index.mjs crates            仅 src-tauri/crates/
//   node scripts/structure-index.mjs --max-exports 4   每文件保留的导出名数量（默认 6）
//   node scripts/structure-index.mjs --out <path>      改输出路径（默认 docs/CODE-INDEX.md）
//
// 跳过：测试文件、生成物、组件样式（`*.module.css`）。

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DEFAULT_OUT = "docs/CODE-INDEX.md";

const SKIP_DIRS = new Set([
  "node_modules",
  "target",
  "dist",
  ".git",
  "temp-backup",
]);

function parseArgs(argv) {
  const opts = { scope: "all", out: DEFAULT_OUT, maxExports: 6 };
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === "--out") opts.out = argv[++i];
    else if (arg === "--max-exports") opts.maxExports = Number(argv[++i]) || 6;
    else if (!arg.startsWith("--")) opts.scope = arg;
  }
  return opts;
}

function walk(dir, predicate, acc = []) {
  let entries;
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch {
    return acc;
  }
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (SKIP_DIRS.has(entry.name)) continue;
      walk(full, predicate, acc);
    } else if (predicate(entry.name)) {
      acc.push(full);
    }
  }
  return acc;
}

function relPosix(file) {
  return path.relative(ROOT, file).split(path.sep).join("/");
}

function countLines(text) {
  if (!text) return 0;
  const rows = text.split("\n");
  return text.endsWith("\n") ? rows.length - 1 : rows.length;
}

function isTest(rel) {
  return (
    rel.includes("__tests__/") ||
    rel.includes("/tests/") ||
    rel.startsWith("src-tauri/tests/") ||
    /\.test\.(ts|tsx)$/.test(rel)
  );
}

function isGenerated(rel, text) {
  if (rel.endsWith(".contract.ts") || rel.includes(".generated.")) return true;
  const head = text.slice(0, 300);
  return head.includes("generated by [ts-rs]") || head.includes("@generated");
}

const TS_ROLE_RULES = [
  [/(^|\/)index\.tsx$/, "视图入口"],
  [/(^|\/)index\.ts$/, "桶出口"],
  [/\.service\.ts$/, "纯逻辑服务"],
  [/Slice\.ts$/, "状态切片"],
  [/Store\.ts$/, "状态聚合"],
  [/Ports\.ts$/, "端口适配"],
  [/(^|\/)use[A-Z]\w*\.(ts|tsx)$/, "Hook"],
  [/(^|\/)hooks\/\w+\.ts$/, "Hook"],
  [/(^|\/)types?\.ts$/, "类型"],
  [/Types\.ts$/, "类型"],
  [/\.contract\.ts$/, "生成契约"],
  [/\.generated\.ts$/, "生成物"],
  [/(^|\/)constants?\.ts$/, "常量"],
  [/\.data\.ts$/, "数据表"],
  [/\.css$/, "样式"],
];

function tsRole(rel) {
  for (const [re, role] of TS_ROLE_RULES) {
    if (re.test(rel)) return role;
  }
  return rel.endsWith(".tsx") ? "组件" : "逻辑";
}

const RS_ROLE_RULES = [
  [/(^|\/)lib\.rs$/, "crate 入口"],
  [/(^|\/)mod\.rs$/, "模块聚合"],
  [/build\.rs$/, "构建脚本"],
  [/\/tests\/|\/tests\.rs$/, "集成测试"],
  [/\bdto\.rs$|\/dto\//, "契约 DTO"],
  [/conf\.rs$/, "配置组"],
  [/_ops\.rs$/, "库操作"],
  [/_store\.rs$/, "持久化"],
];

function rsRole(rel) {
  for (const [re, role] of RS_ROLE_RULES) {
    if (re.test(rel)) return role;
  }
  return "实现";
}

const TS_EXPORT_RE =
  /^\s*export\s+(?:async\s+)?(?:function|const|let|class|interface|type|enum)\s+([A-Za-z_$][\w$]*)/gm;
const TS_EXPORT_LIST_RE = /^\s*export\s+(?:type\s+)?\{([^}]+)\}/gm;
const RS_EXPORT_RE =
  /^\s*pub(?:\([^)]*\))?\s+(?:async\s+)?(?:unsafe\s+)?(?:fn|struct|enum|trait|const|static|type|mod)\s+([A-Za-z_]\w*)/gm;

function tsExports(text, max) {
  const names = [];
  for (const m of text.matchAll(TS_EXPORT_RE)) names.push(m[1]);
  for (const m of text.matchAll(TS_EXPORT_LIST_RE)) {
    for (const raw of m[1].split(",")) {
      const name = raw
        .trim()
        .split(/\s+as\s+/)
        .pop();
      if (name) names.push(name);
    }
  }
  return names.slice(0, max);
}

function rsExports(text, max) {
  const names = [];
  for (const m of text.matchAll(RS_EXPORT_RE)) names.push(m[1]);
  return names.slice(0, max);
}

function cell(value) {
  return value.replace(/\|/g, "\\|");
}

function fmtKeywords(names) {
  if (!names.length) return "-";
  return [...new Set(names)].join("、");
}

// ---------------------------------------------------------------- frontend

function frontendDomain(rel) {
  const segs = rel.replace(/^src\//, "").split("/");
  if (segs.length === 1) return "src 根";
  if (["tools", "vault", "features"].includes(segs[0])) {
    return segs.length > 2 ? `${segs[0]}/${segs[1]}` : segs[0];
  }
  return segs[0];
}

function frontendItems(opts) {
  const files = walk(path.join(ROOT, "src"), (name) =>
    /\.(ts|tsx|css)$/.test(name),
  );
  const items = [];
  let skipped = 0;
  for (const file of files) {
    const rel = relPosix(file);
    if (rel.endsWith(".module.css")) {
      skipped += 1;
      continue;
    }
    const text = fs.readFileSync(file, "utf8");
    if (isTest(rel) || isGenerated(rel, text)) {
      skipped += 1;
      continue;
    }
    items.push({
      rel,
      domain: frontendDomain(rel),
      role: tsRole(rel),
      keywords:
        path.extname(rel) === ".css"
          ? "-"
          : fmtKeywords(tsExports(text, opts.maxExports)),
      lines: countLines(text),
    });
  }
  items.sort(
    (a, b) => a.domain.localeCompare(b.domain) || a.rel.localeCompare(b.rel),
  );
  return { items, skipped };
}

// ---------------------------------------------------------------- rust

function rustDomain(rel, scope) {
  const crateMatch = /^src-tauri\/crates\/([^/]+)\//.exec(rel);
  if (crateMatch) {
    const after = rel
      .slice(crateMatch[0].length)
      .replace(/^src\//, "")
      .split("/");
    if (scope === "crates") return after.length > 1 ? `${after[0]}/` : "(根)";
    return after.length > 1 ? `${crateMatch[1]}/${after[0]}` : crateMatch[1];
  }
  const appSegs = rel.replace(/^src-tauri\//, "").split("/");
  if (appSegs[0] === "src") {
    if (appSegs.length === 2) return "src 根";
    return scope === "app" ? appSegs[1] : `app/${appSegs[1]}`;
  }
  return "src-tauri 根";
}

function rustItems(opts, scope) {
  const files = walk(path.join(ROOT, "src-tauri"), (name) =>
    name.endsWith(".rs"),
  );
  const items = [];
  let skipped = 0;
  for (const file of files) {
    const rel = relPosix(file);
    if (isTest(rel)) {
      skipped += 1;
      continue;
    }
    const text = fs.readFileSync(file, "utf8");
    items.push({
      rel,
      domain: rustDomain(rel, scope),
      role: rsRole(rel),
      keywords: fmtKeywords(rsExports(text, opts.maxExports)),
      lines: countLines(text),
    });
  }
  const rank = (key) => (key === "src 根" ? 0 : key === "src-tauri 根" ? 1 : 2);
  items.sort(
    (a, b) =>
      rank(a.domain) - rank(b.domain) ||
      a.domain.localeCompare(b.domain) ||
      a.rel.localeCompare(b.rel),
  );
  return { items, skipped };
}

// ---------------------------------------------------------------- render

function fileTable(items) {
  const out = [
    "| 路径 | 领域 | 角色 | 关键导出 | 行数 |",
    "|---|---|---|---|---|",
  ];
  for (const i of items) {
    out.push(
      `| \`${i.rel}\` | ${cell(i.domain)} | ${i.role} | ${cell(i.keywords)} | ${i.lines} |`,
    );
  }
  return out.join("\n");
}

function splitDomain(domain, kind) {
  if (kind === "rust") {
    if (domain === "src 根" || domain === "src-tauri 根") return [domain, null];
    if (domain.startsWith("app/")) return ["app", domain.slice(4)];
  }
  const segs = domain.split("/");
  return [segs[0], segs[1] ?? null];
}

function domainOverview(items, kind) {
  const groups = new Map();
  for (const i of items) {
    const [top, sub] = splitDomain(i.domain, kind);
    const g = groups.get(top) ?? { files: 0, lines: 0, subs: new Map() };
    g.files += 1;
    g.lines += i.lines;
    if (sub) {
      const s = g.subs.get(sub) ?? { files: 0, lines: 0 };
      s.files += 1;
      s.lines += i.lines;
      g.subs.set(sub, s);
    }
    groups.set(top, g);
  }
  const tokens = [];
  for (const [top, g] of groups) {
    const head = `**\`${top}\`** ${g.files}/${g.lines}`;
    if (!g.subs.size) {
      tokens.push(head);
      continue;
    }
    const subs = [...g.subs]
      .map(([name, s]) => `\`${name}\` ${s.files}/${s.lines}`)
      .join(" · ");
    tokens.push(`${head}（${subs}）`);
  }
  const totalLines = items.reduce((n, i) => n + i.lines, 0);
  return [
    "**领域规模**（文件数 / 行数，括号内为子域）：",
    "",
    tokens.join(" · "),
    "",
    `**合计** ${items.length} 个文件 / ${totalLines} 行。`,
  ].join("\n");
}

function section(title, intro, items, kind) {
  return [
    `## ${title}`,
    "",
    intro,
    "",
    "### 领域概览",
    "",
    domainOverview(items, kind),
    "",
    "### 逐文件",
    "",
    fileTable(items),
  ].join("\n");
}

function main() {
  const opts = parseArgs(process.argv.slice(2));
  const wantFrontend = ["all", "frontend"].includes(opts.scope);
  const wantRust = ["all", "rust", "app", "crates"].includes(opts.scope);
  const parts = [];

  const head = [
    "# 代码结构索引（脚本生成）",
    "",
    "> 全文由 `node scripts/structure-index.mjs` 生成，**请勿手改**；代码变动后重跑即刷新。",
    `> 生成时间：${new Date().toISOString()}｜范围：${opts.scope}｜单文件导出名上限：${opts.maxExports}`,
    "> 口径：只做机械提取（路径 → 领域 / 角色 / 关键导出 / 行数）；跳过测试、生成物与 `*.module.css`。",
    "> 语义（分层、边界、依赖方向、改动路由）见 `docs/CODE-STRUCTURE.md`。",
    "",
  ].join("\n");

  let total = 0;
  if (wantFrontend) {
    const { items, skipped } = frontendItems(opts);
    total += items.length;
    parts.push(
      section(
        "1. 前端 `src/`",
        `共 ${items.length} 个文件（跳过测试 / 生成物 / 组件样式 ${skipped} 个）。`,
        items,
        "frontend",
      ),
    );
  }
  if (wantRust) {
    const scope = opts.scope === "all" ? "rust" : opts.scope;
    const { items, skipped } = rustItems(opts, scope);
    total += items.length;
    parts.push(
      section(
        wantFrontend ? "2. 后端 `src-tauri/`" : "1. 后端 `src-tauri/`",
        `共 ${items.length} 个文件（跳过测试 ${skipped} 个）。`,
        items,
        "rust",
      ),
    );
  }

  const outPath = path.join(ROOT, opts.out);
  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, `${head}\n${parts.join("\n\n---\n\n")}\n`, "utf8");
  console.log(`已写入 ${opts.out}（${total} 个文件）`);
}

main();
